"""Tests for TSND checkpoint artifact formats.

Embedding artifacts use arrays shaped like (n_units, dim), and yearly graph
artifacts preserve dict fields consumed by downstream modules.
"""
from __future__ import annotations

import logging
import pickle
from collections.abc import Mapping
from pathlib import Path
from typing import cast

import numpy as np
from numpy.typing import NDArray

LOGGER = logging.getLogger(__name__)

EMBEDDING_FILENAME = "embeddings.npz"
GRAPH_FILENAME = "year_graph.pkl"
UNITS_KEY = "units"
MATRIX_KEY = "mat"
GRAPH_VOCAB_KEY = "vocab"
GRAPH_UIDX_KEY = "uidx"
GRAPH_UNIT_DF_KEY = "unit_df"
GRAPH_PAPER_UNITS_KEY = "paper_units"
GRAPH_EDGES_KEY = "edges"
GRAPH_N_PAPERS_KEY = "n_papers"
GRAPH_REQUIRED_KEYS = frozenset(
    (
        GRAPH_VOCAB_KEY,
        GRAPH_UIDX_KEY,
        GRAPH_UNIT_DF_KEY,
        GRAPH_PAPER_UNITS_KEY,
        GRAPH_EDGES_KEY,
        GRAPH_N_PAPERS_KEY,
    )
)
UNIT_GRAPH = "graph"
UNIT_NOVELTY = "novelty"
N_UNITS = 2
EMBEDDING_DIM = 3
EMBEDDING_VALUE_COUNT = N_UNITS * EMBEDDING_DIM
EXPECTED_GRAPH_N_PAPERS = 2
EDGE_LEFT_INDEX = 0
EDGE_RIGHT_INDEX = 1
EDGE_WEIGHT = 2
UNIT_DF_COUNT = 2
PICKLE_PROTOCOL = 4
OBJECT_DTYPE = np.dtype(object)
FLOAT32_DTYPE = np.dtype(np.float32)


def _embedding_artifact() -> dict[str, NDArray[np.object_] | NDArray[np.float32]]:
    """Create a tiny embedding artifact.

    Returns:
        Dict with units shaped like (n_units,) and mat shaped like
        (n_units, dim).
    """
    units = np.array([UNIT_GRAPH, UNIT_NOVELTY], dtype=object)
    matrix = np.arange(EMBEDDING_VALUE_COUNT, dtype=np.float32).reshape(N_UNITS, EMBEDDING_DIM)
    return {UNITS_KEY: units, MATRIX_KEY: matrix}


def _graph_artifact() -> dict[str, object]:
    """Create a tiny yearly graph artifact.

    Returns:
        Graph dict with paper-unit rows shaped like (n_papers, n_units).
    """
    vocab = [UNIT_GRAPH, UNIT_NOVELTY]
    return {
        GRAPH_VOCAB_KEY: vocab,
        GRAPH_UIDX_KEY: {UNIT_GRAPH: EDGE_LEFT_INDEX, UNIT_NOVELTY: EDGE_RIGHT_INDEX},
        GRAPH_UNIT_DF_KEY: {UNIT_GRAPH: UNIT_DF_COUNT, UNIT_NOVELTY: UNIT_DF_COUNT},
        GRAPH_PAPER_UNITS_KEY: [[UNIT_GRAPH, UNIT_NOVELTY], [UNIT_GRAPH]],
        GRAPH_EDGES_KEY: {(EDGE_LEFT_INDEX, EDGE_RIGHT_INDEX): EDGE_WEIGHT},
        GRAPH_N_PAPERS_KEY: EXPECTED_GRAPH_N_PAPERS,
    }


def _load_trusted_pickle(path: Path, trusted_dir: Path) -> Mapping[str, object]:
    """Load a pickle only from the test-created tmp directory.

    Args:
        path: Pickle path generated by this test.
        trusted_dir: Pytest tmp directory that owns the trusted artifact.

    Returns:
        Loaded graph dict preserving fields shaped like (n_fields,).

    Raises:
        ValueError: If the path is outside the trusted tmp directory.
        TypeError: If the loaded object is not a mapping.
    """
    if path.parent != trusted_dir:
        raise ValueError("refusing to load pickle outside trusted tmp_path")
    with path.open("rb") as handle:
        loaded = pickle.load(handle)
    if not isinstance(loaded, Mapping):
        raise TypeError("expected a mapping graph artifact")
    return cast(Mapping[str, object], loaded)


def test_npz_checkpoint_does_round_trip_units_and_matrix(tmp_path: Path) -> None:
    """Assert .npz preserves units (n_units,) and mat (n_units, dim)."""
    artifact = _embedding_artifact()
    output_path = tmp_path / EMBEDDING_FILENAME

    np.savez_compressed(output_path, **artifact)
    with np.load(output_path, allow_pickle=True) as loaded:
        loaded_units = loaded[UNITS_KEY]
        loaded_matrix = loaded[MATRIX_KEY]

    expected_units = artifact[UNITS_KEY]
    expected_matrix = artifact[MATRIX_KEY]
    assert loaded_units.shape == expected_units.shape
    assert loaded_units.dtype == OBJECT_DTYPE
    assert loaded_matrix.shape == expected_matrix.shape
    assert loaded_matrix.dtype == FLOAT32_DTYPE


def test_pkl_graph_checkpoint_does_round_trip_required_keys(tmp_path: Path) -> None:
    """Assert .pkl graph preserves required keys and n_papers scalar."""
    graph = _graph_artifact()
    output_path = tmp_path / GRAPH_FILENAME

    with output_path.open("wb") as handle:
        pickle.dump(graph, handle, protocol=PICKLE_PROTOCOL)
    loaded = _load_trusted_pickle(output_path, tmp_path)

    assert GRAPH_REQUIRED_KEYS <= set(loaded)
    assert loaded[GRAPH_N_PAPERS_KEY] == EXPECTED_GRAPH_N_PAPERS
